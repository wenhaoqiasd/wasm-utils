#!/usr/bin/env node
/**
 * Reads src/wasm/*.wasm and writes src/wasm-bytes/*.js (base64 exports only).
 * Run after `make wasm` or via prepublishOnly.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const wasmDir = resolve(root, "src/wasm");
const outDir = resolve(root, "src/wasm-bytes");

const modules = [
  { wasm: "oklch2rgb.wasm", out: "oklch2rgb.js", exportName: "OKLCH2RGB_WASM_BASE64" },
  { wasm: "rgb2oklch.wasm", out: "rgb2oklch.js", exportName: "RGB2OKLCH_WASM_BASE64" },
  { wasm: "extract-colors.wasm", out: "extract-colors.js", exportName: "EXTRACT_COLORS_WASM_BASE64" },
  { wasm: "squircle-svg.wasm", out: "squircle-svg.js", exportName: "SQUIRCLE_SVG_WASM_BASE64" },
];

function wasmBase64(name) {
  return readFileSync(resolve(wasmDir, name)).toString("base64");
}

mkdirSync(outDir, { recursive: true });

for (const { wasm, out, exportName } of modules) {
  const b64 = wasmBase64(wasm);
  writeFileSync(
    resolve(outDir, out),
    `// AUTO-GENERATED by scripts/embed-wasm-base64.js — do not edit
export const ${exportName} = ${JSON.stringify(b64)};
`,
  );
}

console.log("Embedded WASM base64 into src/wasm-bytes/.");
